-- В категории "Аккаунтская (НЗ запас)" несколько материалов на самом деле
-- краски (гуашь, акрил, белила масляные) — их, как и остальные краски,
-- нельзя точно отмерить на занятии, поэтому переводим на оценочный учёт
-- (капля/горошина/полтюбика/тюбик) и поправляем единицу измерения.

UPDATE public.materials
SET tracking_mode = 'оценочный', unit = 'тюбик'
WHERE category_id = (SELECT id FROM public.material_categories WHERE name = 'Аккаунтская (НЗ запас)')
  AND name IN ('Гуашь белая 500л', 'акрил черный 220мл', 'белила масло тюб. - 170', 'белила масло уп. - 200');
